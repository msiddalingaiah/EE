import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

/**
 * Writes sw.js into the build: a service worker that caches every file of the build (the app,
 * the samples, the public files) when installed, and serves them from the cache, so the
 * installed app runs with no server. A new build has a new cache name, so serving it once
 * updates an installed app (it takes effect the next time the app is opened).
 */
function serviceWorker(): Plugin {
  return {
    name: 'osprey-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = new Set(['./', './index.html']);
      for (const name of Object.keys(bundle)) files.add(`./${name}`);
      for (const name of readdirSync(join(import.meta.dirname, 'public'))) files.add(`./${name}`);
      const list = [...files].sort();
      const version = createHash('sha256').update(list.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts: caches the whole app for use without a server.
const CACHE = 'osprey-${version}';
const FILES = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('osprey-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache first; pages fall back to the app itself. Vary is ignored: the preview server sends
// "Vary: Origin", and the stylesheet and script (crossorigin) are requested with an Origin
// header the cached copies were fetched without, so they would never match.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.open(CACHE).then(async (c) => {
      const hit = await c.match(req, { ignoreSearch: true, ignoreVary: true });
      if (hit) return hit;
      if (req.mode === 'navigate') {
        const page = await c.match('./index.html', { ignoreVary: true });
        if (page) return page;
      }
      return fetch(req);
    }),
  );
});
`,
      });
    },
  };
}

export default defineConfig({
  // Relative URLs, so the build works from any folder or port.
  base: './',
  plugins: [serviceWorker()],
  test: {
    environment: 'jsdom',
    include: ['test/**/*.test.ts'],
    exclude: ['test/ui/**', 'node_modules/**'],
  },
});
